"""The practice table, as a SQLAlchemy model (Stage 3, lesson A7).

Alembic's migrations in versions/ build the table; this model describes what the table should look like.
"alembic check" compares the two and says whether a new migration is needed.
"""

from datetime import date, datetime

from sqlalchemy import DateTime, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class Note(Base):
    __tablename__ = "practice_note"

    id: Mapped[int] = mapped_column(primary_key=True)
    body: Mapped[str]
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    author: Mapped[str | None]  # "| None": the column may be NULL. Added by migration 0002
    due_on: Mapped[date | None]  # added by an autogenerated migration (Stage 3, step C7)